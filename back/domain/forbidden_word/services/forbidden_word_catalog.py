def _slugify(value: str) -> str:
    ligatures = value.replace("œ", "oe").replace("Œ", "Oe").replace("æ", "ae").replace("Æ", "Ae")
    ascii_value = unicodedata.normalize("NFKD", ligatures).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_value.lower()).strip("-")


